export type Hex = `0x${string}`;
export type Item = {
  id: string;
  operator: Hex;
  arbiter: Hex;
  fee: string;
  deposit: string;
  reserveBps: number;
  disputeWindow: number;
  active: boolean;
  rented: boolean;
  reserve: string;
  metadataURI: string;
  name: string;
  description: string;
  category: "camera" | "printer" | "tool";
  image?: string;
};
export type Rental = {
  id: string;
  itemId: string;
  renter: Hex;
  deposit: string;
  startedAt: number;
  refundAt: number;
  status: number;
  cronJobId: string;
  dispute?: {
    amount: string;
    evidenceHash: Hex;
    renterVoted: boolean;
    renterApproved: boolean;
    arbiterVoted: boolean;
    arbiterApproved: boolean;
  };
};
export type Repair = {
  id: string;
  itemId: string;
  repairer: Hex;
  amount: string;
  receiptHash: Hex;
  paid: boolean;
  rejected: boolean;
};
export type LedgerEvent = {
  id: string;
  name: string;
  transactionHash: Hex | null;
  blockHash: Hex | null;
  blockNumber: string;
  eventIndex: number | null;
  args: Record<string, string | number | boolean>;
  source: "substrate" | "evm" | "indexer";
};
export type NativeEvidenceCapability = {
  maxBytes: number;
  retentionBlocks: number;
  probeTxHash: Hex;
  probeBlockHash: Hex;
  probeBytes: number;
};
export type PublicConfig = {
  chainId: number;
  network: string;
  meterMend: Hex | null;
  cronpot: Hex | null;
  wssUrl: string;
  evmRpcUrl: string;
  explorer: string;
  cronpotMode: "native" | "keeper" | "unverified";
  cronTip: string | null;
  nativeDecimals: number;
  evmDecimals: number;
  unitsVerified: boolean;
  storageConfigured: boolean;
  nativeEvidence: NativeEvidenceCapability | null;
  appUrl: string | null;
  deploymentBlock: string | null;
};
export type Ledger = {
  config: PublicConfig;
  state: "unconfigured" | "ready" | "error";
  observedAt: string;
  block: string | null;
  blockTimestamp: number | null;
  items: Item[];
  rentals: Rental[];
  repairs: Repair[];
  events: LedgerEvent[];
  historyStatus: string;
  error?: string;
  jobs: Array<Record<string, unknown>>;
  jobsError?: string;
  automaticRefundCount: number | null;
};
export type WalletIdentity = {
  address: string;
  name?: string;
  h160: Hex | null;
  mapped: boolean | null;
  autoMap: boolean | null;
  nativeBalance: string | null;
};
export type TxReceipt = { txHash: string; block: unknown; events?: unknown };
